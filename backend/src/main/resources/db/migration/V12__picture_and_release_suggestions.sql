-- Phase 8: pictures found at TCGplayer for cards and products without one, and suggestions for the release calendar.
-- Only new tables and new nullable columns, so the previous version keeps working on this schema after a rollback.

-- A picture found by the picture search. It comes after the source's own picture and after an upload, and a sync
-- never touches it.
ALTER TABLE cards ADD COLUMN found_image_small_url VARCHAR(500);
ALTER TABLE cards ADD COLUMN found_image_large_url VARCHAR(500);

-- A match the picture search wasn't sure about: the admin picks one of the candidates, or none.
CREATE TABLE picture_suggestions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game       VARCHAR(20)                 NOT NULL,
    card_id    BIGINT,
    product_id BIGINT,
    status     VARCHAR(20)                 NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    decided_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_picture_suggestions_card FOREIGN KEY (card_id) REFERENCES cards (id),
    CONSTRAINT fk_picture_suggestions_product FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE INDEX idx_picture_suggestions_status_game ON picture_suggestions (status, game);
CREATE INDEX idx_picture_suggestions_card_id ON picture_suggestions (card_id);
CREATE INDEX idx_picture_suggestions_product_id ON picture_suggestions (product_id);

CREATE TABLE picture_suggestion_candidates (
    suggestion_id BIGINT       NOT NULL,
    position      INTEGER      NOT NULL,
    tcgplayer_id  BIGINT       NOT NULL,
    name          VARCHAR(300) NOT NULL,
    score         INTEGER      NOT NULL,
    PRIMARY KEY (suggestion_id, position),
    CONSTRAINT fk_picture_suggestion_candidates_suggestion FOREIGN KEY (suggestion_id) REFERENCES picture_suggestions (id)
);

-- Upcoming sets from the card sources and TCGplayer, for the admin to add to the release calendar or dismiss.
CREATE TABLE release_suggestions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game         VARCHAR(20)                 NOT NULL,
    name         VARCHAR(150)                NOT NULL,
    name_key     VARCHAR(150)                NOT NULL,
    release_date DATE                        NOT NULL,
    source       VARCHAR(20)                 NOT NULL,
    set_code     VARCHAR(50),
    dismissed    BOOLEAN                     NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_release_suggestions_game_key UNIQUE (game, name_key)
);
