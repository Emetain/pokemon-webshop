ALTER TABLE users ADD COLUMN collection_share_slug VARCHAR(64);
ALTER TABLE users ADD CONSTRAINT uk_users_collection_share_slug UNIQUE (collection_share_slug);

CREATE TABLE collection_entries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT                      NOT NULL,
    card_id        BIGINT                      NOT NULL,
    variant        VARCHAR(30)                 NOT NULL,
    quantity       INTEGER                     NOT NULL,
    card_condition VARCHAR(20),
    added_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_collection_entries_user_card_variant UNIQUE (user_id, card_id, variant),
    CONSTRAINT fk_collection_entries_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_collection_entries_card FOREIGN KEY (card_id) REFERENCES cards (id)
);

CREATE INDEX idx_collection_entries_card_id ON collection_entries (card_id);

CREATE TABLE card_wishlist_entries (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT                      NOT NULL,
    card_id  BIGINT                      NOT NULL,
    added_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_card_wishlist_entries_user_card UNIQUE (user_id, card_id),
    CONSTRAINT fk_card_wishlist_entries_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_card_wishlist_entries_card FOREIGN KEY (card_id) REFERENCES cards (id)
);

CREATE TABLE binder_selections (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT                      NOT NULL,
    card_id  BIGINT                      NOT NULL,
    added_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_binder_selections_user_card UNIQUE (user_id, card_id),
    CONSTRAINT fk_binder_selections_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_binder_selections_card FOREIGN KEY (card_id) REFERENCES cards (id)
);

CREATE TABLE collection_value_snapshots (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL,
    snapshot_date DATE   NOT NULL,
    value_cents   BIGINT NOT NULL,
    CONSTRAINT uk_collection_value_snapshots_user_date UNIQUE (user_id, snapshot_date),
    CONSTRAINT fk_collection_value_snapshots_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE pokemon_species (
    dex_number INTEGER      NOT NULL PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    generation INTEGER      NOT NULL
);

