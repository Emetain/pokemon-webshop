CREATE SEQUENCE product_stock_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE product_stock (
    id       BIGINT  NOT NULL PRIMARY KEY,
    on_hand  INTEGER NOT NULL,
    reserved INTEGER NOT NULL,
    version  BIGINT  NOT NULL
);

CREATE SEQUENCE products_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE products (
    id                  BIGINT                      NOT NULL PRIMARY KEY,
    game                VARCHAR(20),
    type                VARCHAR(30)                 NOT NULL,
    name                VARCHAR(255)                NOT NULL,
    name_search         VARCHAR(255)                NOT NULL,
    slug                VARCHAR(200)                NOT NULL,
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    stock_id            BIGINT                      NOT NULL,
    accessory_type      VARCHAR(30),
    description         VARCHAR(10000),
    language            VARCHAR(5),
    set_id              BIGINT,
    card_id             BIGINT,
    card_variant        VARCHAR(30),
    card_condition      VARCHAR(20),
    grading_company     VARCHAR(10),
    grade               VARCHAR(20),
    price_cents         BIGINT,
    sale_price_cents    BIGINT,
    status              VARCHAR(20)                 NOT NULL,
    pre_order           BOOLEAN                     NOT NULL,
    release_date        DATE,
    ships_from          DATE,
    arrived_at          TIMESTAMP(6) WITH TIME ZONE,
    low_stock_threshold INTEGER                     NOT NULL,
    import_source       VARCHAR(20),
    import_key          VARCHAR(64),
    edited_by_admin     BOOLEAN                     NOT NULL,
    CONSTRAINT uk_products_slug UNIQUE (slug),
    CONSTRAINT uk_products_import UNIQUE (import_source, import_key),
    CONSTRAINT uk_products_stock_id UNIQUE (stock_id),
    CONSTRAINT fk_products_stock FOREIGN KEY (stock_id) REFERENCES product_stock (id),
    CONSTRAINT fk_products_set FOREIGN KEY (set_id) REFERENCES card_sets (id),
    CONSTRAINT fk_products_card FOREIGN KEY (card_id) REFERENCES cards (id)
);

CREATE INDEX idx_products_status_game_type ON products (status, game, type);
CREATE INDEX idx_products_set_id ON products (set_id);
CREATE INDEX idx_products_card_id ON products (card_id);
CREATE INDEX idx_products_created_at ON products (created_at);
CREATE INDEX idx_products_arrived_at ON products (arrived_at);
CREATE INDEX idx_products_name_search ON products (name_search);

CREATE TABLE product_images (
    product_id BIGINT       NOT NULL,
    position   INTEGER      NOT NULL,
    url        VARCHAR(500) NOT NULL,
    PRIMARY KEY (product_id, position),
    CONSTRAINT fk_product_images_product FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE TABLE stock_movements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      BIGINT                      NOT NULL,
    quantity_change INTEGER                     NOT NULL,
    reason          VARCHAR(20)                 NOT NULL,
    on_hand_after   INTEGER                     NOT NULL,
    reserved_after  INTEGER                     NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    note            VARCHAR(500),
    admin_user_id   BIGINT,
    CONSTRAINT fk_stock_movements_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_stock_movements_admin_user FOREIGN KEY (admin_user_id) REFERENCES users (id)
);

CREATE INDEX idx_stock_movements_product_created ON stock_movements (product_id, created_at);
CREATE INDEX idx_stock_movements_created_at ON stock_movements (created_at);

CREATE TABLE product_wishlist_entries (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                      NOT NULL,
    product_id BIGINT                      NOT NULL,
    added_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_product_wishlist_entries_user_product UNIQUE (user_id, product_id),
    CONSTRAINT fk_product_wishlist_entries_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_product_wishlist_entries_product FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE INDEX idx_product_wishlist_entries_product_id ON product_wishlist_entries (product_id);

CREATE TABLE stock_alerts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT                      NOT NULL,
    email       VARCHAR(254)                NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    notified_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_stock_alerts_product_email UNIQUE (product_id, email),
    CONSTRAINT fk_stock_alerts_product FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE TABLE hero_slides (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(120)                NOT NULL,
    position     INTEGER                     NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    text         VARCHAR(300),
    button_label VARCHAR(40),
    link_url     VARCHAR(300),
    image_url    VARCHAR(500),
    game         VARCHAR(20),
    active       BOOLEAN                     NOT NULL,
    starts_at    TIMESTAMP(6) WITH TIME ZONE,
    ends_at      TIMESTAMP(6) WITH TIME ZONE
);
