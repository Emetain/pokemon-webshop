CREATE TABLE carts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT,
    guest_token_hash VARCHAR(64),
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_carts_user_id UNIQUE (user_id),
    CONSTRAINT uk_carts_guest_token_hash UNIQUE (guest_token_hash),
    CONSTRAINT fk_carts_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_carts_updated_at ON carts (updated_at);

CREATE TABLE cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id    BIGINT                      NOT NULL,
    product_id BIGINT                      NOT NULL,
    quantity   INTEGER                     NOT NULL,
    added_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_cart_items_cart_product UNIQUE (cart_id, product_id),
    CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id) REFERENCES carts (id),
    CONSTRAINT fk_cart_items_product FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE INDEX idx_cart_items_product_id ON cart_items (product_id);

CREATE TABLE shipping_rates (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country         VARCHAR(2)                  NOT NULL,
    price_cents     BIGINT                      NOT NULL,
    free_from_cents BIGINT,
    delivery_time   VARCHAR(200)                NOT NULL,
    active          BOOLEAN                     NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_shipping_rates_country UNIQUE (country)
);

CREATE TABLE orders (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number                    VARCHAR(20)                 NOT NULL,
    user_id                   BIGINT,
    email                     VARCHAR(254)                NOT NULL,
    customer_name             VARCHAR(100)                NOT NULL,
    street                    VARCHAR(100)                NOT NULL,
    house_number              VARCHAR(20)                 NOT NULL,
    postcode                  VARCHAR(10)                 NOT NULL,
    city                      VARCHAR(100)                NOT NULL,
    country                   VARCHAR(2)                  NOT NULL,
    subtotal_cents            BIGINT                      NOT NULL,
    shipping_cents            BIGINT                      NOT NULL,
    total_cents               BIGINT                      NOT NULL,
    vat_cents                 BIGINT                      NOT NULL,
    delivery_time             VARCHAR(200),
    shipment_preference       VARCHAR(20)                 NOT NULL,
    access_token              VARCHAR(64)                 NOT NULL,
    cart_id                   BIGINT,
    terms_accepted_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at                TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at                TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status                    VARCHAR(20)                 NOT NULL,
    stock_state               VARCHAR(20)                 NOT NULL,
    reserved_until            TIMESTAMP(6) WITH TIME ZONE,
    stripe_session_id         VARCHAR(255),
    stripe_session_expires_at TIMESTAMP(6) WITH TIME ZONE,
    stripe_payment_intent_id  VARCHAR(255),
    payment_method            VARCHAR(40),
    paid_at                   TIMESTAMP(6) WITH TIME ZONE,
    shipped_at                TIMESTAMP(6) WITH TIME ZONE,
    delivered_at              TIMESTAMP(6) WITH TIME ZONE,
    cancelled_at              TIMESTAMP(6) WITH TIME ZONE,
    refunded_cents            BIGINT                      NOT NULL,
    carrier                   VARCHAR(20),
    tracking_code             VARCHAR(100),
    tracking_url              VARCHAR(500),
    CONSTRAINT uk_orders_number UNIQUE (number),
    CONSTRAINT uk_orders_access_token UNIQUE (access_token),
    CONSTRAINT uk_orders_stripe_session_id UNIQUE (stripe_session_id),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_orders_user_created ON orders (user_id, created_at);
CREATE INDEX idx_orders_status_created ON orders (status, created_at);
CREATE INDEX idx_orders_paid_at ON orders (paid_at);
CREATE INDEX idx_orders_cart_status ON orders (cart_id, status);
CREATE INDEX idx_orders_stock_reserved_until ON orders (stock_state, reserved_until);
CREATE INDEX idx_orders_email ON orders (email);

CREATE TABLE order_lines (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT       NOT NULL,
    product_id       BIGINT       NOT NULL,
    product_name     VARCHAR(255) NOT NULL,
    product_slug     VARCHAR(200) NOT NULL,
    product_type     VARCHAR(30)  NOT NULL,
    image_url        VARCHAR(500),
    image_is_card    BOOLEAN      NOT NULL,
    unit_price_cents BIGINT       NOT NULL,
    quantity         INTEGER      NOT NULL,
    line_total_cents BIGINT       NOT NULL,
    pre_order        BOOLEAN      NOT NULL,
    ships_from       DATE,
    CONSTRAINT fk_order_lines_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_lines_product FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE INDEX idx_order_lines_order_id ON order_lines (order_id);
CREATE INDEX idx_order_lines_product_id ON order_lines (product_id);

CREATE TABLE order_status_changes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT                      NOT NULL,
    status        VARCHAR(20)                 NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    note          VARCHAR(500),
    admin_user_id BIGINT,
    CONSTRAINT fk_order_status_changes_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_status_changes_admin_user FOREIGN KEY (admin_user_id) REFERENCES users (id)
);

CREATE INDEX idx_order_status_changes_order_id ON order_status_changes (order_id);
