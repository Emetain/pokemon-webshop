CREATE TABLE drops (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(120)                NOT NULL,
    slug                 VARCHAR(140)                NOT NULL,
    starts_at            TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    description          VARCHAR(5000),
    banner_url           VARCHAR(500),
    ends_at              TIMESTAMP(6) WITH TIME ZONE,
    status               VARCHAR(20)                 NOT NULL,
    requires_account     BOOLEAN                     NOT NULL,
    max_per_customer     INTEGER,
    leftover             VARCHAR(20)                 NOT NULL,
    show_in_hero         BOOLEAN                     NOT NULL,
    admit_per_minute     INTEGER                     NOT NULL,
    queue_paused         BOOLEAN                     NOT NULL,
    started_at           TIMESTAMP(6) WITH TIME ZONE,
    ended_at             TIMESTAMP(6) WITH TIME ZONE,
    end_reason           VARCHAR(200),
    shuffled_at          TIMESTAMP(6) WITH TIME ZONE,
    shuffled_count       INTEGER                     NOT NULL,
    next_position        BIGINT                      NOT NULL,
    admitted_up_to       BIGINT                      NOT NULL,
    admitted_until       TIMESTAMP(6) WITH TIME ZONE,
    reminders_sent_at    TIMESTAMP(6) WITH TIME ZONE,
    leftover_returned_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_drops_slug UNIQUE (slug)
);

CREATE INDEX idx_drops_status_starts_at ON drops (status, starts_at);

CREATE TABLE drop_products (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drop_id          BIGINT  NOT NULL,
    product_id       BIGINT  NOT NULL,
    position         INTEGER NOT NULL,
    allocated        INTEGER NOT NULL,
    reserved         INTEGER NOT NULL,
    sold             INTEGER NOT NULL,
    max_per_customer INTEGER,
    price_cents      BIGINT,
    sold_out_at      TIMESTAMP(6) WITH TIME ZONE,
    version          BIGINT  NOT NULL,
    CONSTRAINT uk_drop_products_drop_product UNIQUE (drop_id, product_id),
    CONSTRAINT fk_drop_products_drop FOREIGN KEY (drop_id) REFERENCES drops (id),
    CONSTRAINT fk_drop_products_product FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE INDEX idx_drop_products_product_id ON drop_products (product_id);

CREATE TABLE drop_queue_entries (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drop_id            BIGINT                      NOT NULL,
    user_id            BIGINT,
    visitor_token_hash VARCHAR(64),
    joined_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_seen_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    position           BIGINT,
    admitted_at        TIMESTAMP(6) WITH TIME ZONE,
    access_token_hash  VARCHAR(64),
    access_expires_at  TIMESTAMP(6) WITH TIME ZONE,
    join_count         INTEGER                     NOT NULL,
    CONSTRAINT uk_drop_queue_entries_drop_user UNIQUE (drop_id, user_id),
    CONSTRAINT uk_drop_queue_entries_drop_visitor UNIQUE (drop_id, visitor_token_hash),
    CONSTRAINT uk_drop_queue_entries_access_token UNIQUE (access_token_hash),
    CONSTRAINT fk_drop_queue_entries_drop FOREIGN KEY (drop_id) REFERENCES drops (id),
    CONSTRAINT fk_drop_queue_entries_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_drop_queue_entries_drop_position ON drop_queue_entries (drop_id, position);

CREATE TABLE drop_cart_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id        BIGINT                      NOT NULL,
    drop_product_id BIGINT                      NOT NULL,
    quantity        INTEGER                     NOT NULL,
    added_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_drop_cart_items_entry_product UNIQUE (entry_id, drop_product_id),
    CONSTRAINT fk_drop_cart_items_entry FOREIGN KEY (entry_id) REFERENCES drop_queue_entries (id),
    CONSTRAINT fk_drop_cart_items_drop_product FOREIGN KEY (drop_product_id) REFERENCES drop_products (id)
);

CREATE INDEX idx_drop_cart_items_drop_product_id ON drop_cart_items (drop_product_id);

CREATE TABLE drop_reminders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drop_id    BIGINT                      NOT NULL,
    email      VARCHAR(254)                NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    sent_at    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_drop_reminders_drop_email UNIQUE (drop_id, email),
    CONSTRAINT fk_drop_reminders_drop FOREIGN KEY (drop_id) REFERENCES drops (id)
);

