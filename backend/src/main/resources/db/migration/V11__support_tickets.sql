-- Phase 8: customer service tickets. The customer follows a ticket with a secret link, the shop answers in admin.
-- The chatbot stores nothing: only its cost goes into ai_usage, as kind CHAT. Only new tables, so the previous
-- version keeps working on this schema after a rollback.

CREATE TABLE support_tickets (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number       VARCHAR(20)                 NOT NULL,
    access_token VARCHAR(64)                 NOT NULL,
    name         VARCHAR(100)                NOT NULL,
    email        VARCHAR(254)                NOT NULL,
    subject      VARCHAR(150)                NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    user_id      BIGINT,
    order_number VARCHAR(20),
    status       VARCHAR(20)                 NOT NULL,
    CONSTRAINT uk_support_tickets_number UNIQUE (number),
    CONSTRAINT uk_support_tickets_access_token UNIQUE (access_token),
    CONSTRAINT fk_support_tickets_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_support_tickets_status_updated ON support_tickets (status, updated_at);
CREATE INDEX idx_support_tickets_user_id ON support_tickets (user_id);

CREATE TABLE support_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  BIGINT                      NOT NULL,
    from_shop  BOOLEAN                     NOT NULL,
    body       VARCHAR(10000)              NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    author_id  BIGINT,
    CONSTRAINT fk_support_messages_ticket FOREIGN KEY (ticket_id) REFERENCES support_tickets (id),
    CONSTRAINT fk_support_messages_author FOREIGN KEY (author_id) REFERENCES users (id)
);

CREATE INDEX idx_support_messages_ticket_id ON support_messages (ticket_id);
