CREATE TABLE card_sets (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game         VARCHAR(20)  NOT NULL,
    external_id  VARCHAR(100) NOT NULL,
    code         VARCHAR(50)  NOT NULL,
    name         VARCHAR(255) NOT NULL,
    series       VARCHAR(100) NOT NULL,
    release_date DATE,
    card_count   INTEGER      NOT NULL,
    logo_url     VARCHAR(500),
    symbol_url   VARCHAR(500),
    sort_order   INTEGER      NOT NULL,
    CONSTRAINT uk_card_sets_game_external_id UNIQUE (game, external_id),
    CONSTRAINT uk_card_sets_game_code UNIQUE (game, code)
);

CREATE INDEX idx_card_sets_game_release_date ON card_sets (game, release_date);

CREATE SEQUENCE cards_seq START WITH 1 INCREMENT BY 500;

CREATE TABLE cards (
    id              BIGINT       NOT NULL PRIMARY KEY,
    game            VARCHAR(20)  NOT NULL,
    set_id          BIGINT       NOT NULL,
    external_id     VARCHAR(255) NOT NULL,
    number          VARCHAR(50)  NOT NULL,
    name            VARCHAR(255) NOT NULL,
    name_search     VARCHAR(255) NOT NULL,
    sort_key        VARCHAR(100) NOT NULL,
    rarity          VARCHAR(50),
    card_type       VARCHAR(255),
    category        VARCHAR(50),
    image_small_url VARCHAR(500),
    image_large_url VARCHAR(500),
    sort_price_cents BIGINT,
    CONSTRAINT uk_cards_game_external_id UNIQUE (game, external_id),
    CONSTRAINT fk_cards_set FOREIGN KEY (set_id) REFERENCES card_sets (id)
);

CREATE INDEX idx_cards_set_sort_key ON cards (set_id, sort_key);
CREATE INDEX idx_cards_game_rarity ON cards (game, rarity);
CREATE INDEX idx_cards_game_category ON cards (game, category);
CREATE INDEX idx_cards_game_name_search ON cards (game, name_search);
CREATE INDEX idx_cards_name_search ON cards (name_search);

CREATE TABLE card_variants (
    card_id BIGINT      NOT NULL,
    variant VARCHAR(30) NOT NULL,
    PRIMARY KEY (card_id, variant),
    CONSTRAINT fk_card_variants_card FOREIGN KEY (card_id) REFERENCES cards (id)
);

CREATE INDEX idx_card_variants_variant ON card_variants (variant);

CREATE TABLE card_colors (
    card_id BIGINT      NOT NULL,
    color   VARCHAR(30) NOT NULL,
    PRIMARY KEY (card_id, color),
    CONSTRAINT fk_card_colors_card FOREIGN KEY (card_id) REFERENCES cards (id)
);

CREATE INDEX idx_card_colors_color ON card_colors (color);

CREATE TABLE card_dex_numbers (
    card_id    BIGINT  NOT NULL,
    dex_number INTEGER NOT NULL,
    PRIMARY KEY (card_id, dex_number),
    CONSTRAINT fk_card_dex_numbers_card FOREIGN KEY (card_id) REFERENCES cards (id)
);

CREATE INDEX idx_card_dex_numbers_dex_number ON card_dex_numbers (dex_number);

CREATE SEQUENCE card_prices_seq START WITH 1 INCREMENT BY 500;

CREATE TABLE card_prices (
    id            BIGINT                      NOT NULL PRIMARY KEY,
    card_id       BIGINT                      NOT NULL,
    variant       VARCHAR(30)                 NOT NULL,
    source        VARCHAR(20)                 NOT NULL,
    currency      VARCHAR(3)                  NOT NULL,
    trend_cents   BIGINT,
    average_cents BIGINT,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_card_prices_card_variant_source UNIQUE (card_id, variant, source),
    CONSTRAINT fk_card_prices_card FOREIGN KEY (card_id) REFERENCES cards (id)
);

CREATE TABLE exchange_rates (
    currency  VARCHAR(3)     NOT NULL PRIMARY KEY,
    per_euro  NUMERIC(12, 6) NOT NULL,
    rate_date DATE           NOT NULL
);

CREATE TABLE sync_runs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game            VARCHAR(20)                 NOT NULL,
    started_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at     TIMESTAMP(6) WITH TIME ZONE,
    status          VARCHAR(20)                 NOT NULL,
    sets_processed  INTEGER                     NOT NULL,
    cards_created   INTEGER                     NOT NULL,
    cards_updated   INTEGER                     NOT NULL,
    cards_unchanged INTEGER                     NOT NULL,
    cards_failed    INTEGER                     NOT NULL,
    prices_stored   INTEGER                     NOT NULL,
    error           VARCHAR(2000)
);

CREATE INDEX idx_sync_runs_game_started_at ON sync_runs (game, started_at);
