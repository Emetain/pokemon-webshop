-- Phase 8: discount codes, mystery boxes, reviews, the release calendar, news, info pages, the newsletter and
-- hero slides written by AI. Only new tables and new columns with a default, so the previous version keeps working
-- on this schema after a rollback.

CREATE TABLE discount_codes (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(40)                 NOT NULL,
    kind                VARCHAR(20)                 NOT NULL,
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    percent             INTEGER,
    amount_cents        BIGINT,
    minimum_order_cents BIGINT,
    starts_at           TIMESTAMP(6) WITH TIME ZONE,
    ends_at             TIMESTAMP(6) WITH TIME ZONE,
    max_uses            INTEGER,
    once_per_customer   BOOLEAN                     NOT NULL,
    applies_to_drops    BOOLEAN                     NOT NULL,
    active              BOOLEAN                     NOT NULL,
    note                VARCHAR(200),
    CONSTRAINT uk_discount_codes_code UNIQUE (code)
);

CREATE TABLE discount_code_games (
    discount_code_id BIGINT      NOT NULL,
    game             VARCHAR(20) NOT NULL,
    PRIMARY KEY (discount_code_id, game),
    CONSTRAINT fk_discount_code_games_code FOREIGN KEY (discount_code_id) REFERENCES discount_codes (id)
);

CREATE TABLE discount_code_product_types (
    discount_code_id BIGINT      NOT NULL,
    product_type     VARCHAR(30) NOT NULL,
    PRIMARY KEY (discount_code_id, product_type),
    CONSTRAINT fk_discount_code_product_types_code FOREIGN KEY (discount_code_id) REFERENCES discount_codes (id)
);

ALTER TABLE orders ADD COLUMN discount_code_id BIGINT;
ALTER TABLE orders ADD COLUMN discount_code VARCHAR(40);
ALTER TABLE orders ADD COLUMN discount_cents BIGINT DEFAULT 0 NOT NULL;
ALTER TABLE orders ADD CONSTRAINT fk_orders_discount_code FOREIGN KEY (discount_code_id) REFERENCES discount_codes (id);
CREATE INDEX idx_orders_discount_code_id ON orders (discount_code_id);

CREATE TABLE mystery_box_batches (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT                      NOT NULL,
    name       VARCHAR(100)                NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_mystery_box_batches_product FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE INDEX idx_mystery_box_batches_product_id ON mystery_box_batches (product_id);

CREATE TABLE mystery_box_prizes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id    BIGINT       NOT NULL,
    name        VARCHAR(150) NOT NULL,
    value_cents BIGINT       NOT NULL,
    box_count   INTEGER      NOT NULL,
    card_id     BIGINT,
    drawn       INTEGER      NOT NULL,
    CONSTRAINT fk_mystery_box_prizes_batch FOREIGN KEY (batch_id) REFERENCES mystery_box_batches (id),
    CONSTRAINT fk_mystery_box_prizes_card FOREIGN KEY (card_id) REFERENCES cards (id)
);

CREATE INDEX idx_mystery_box_prizes_batch_id ON mystery_box_prizes (batch_id);

CREATE TABLE mystery_box_draws (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prize_id      BIGINT                      NOT NULL,
    order_line_id BIGINT                      NOT NULL,
    drawn_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_mystery_box_draws_prize FOREIGN KEY (prize_id) REFERENCES mystery_box_prizes (id),
    CONSTRAINT fk_mystery_box_draws_order_line FOREIGN KEY (order_line_id) REFERENCES order_lines (id)
);

CREATE INDEX idx_mystery_box_draws_order_line_id ON mystery_box_draws (order_line_id);
CREATE INDEX idx_mystery_box_draws_prize_id ON mystery_box_draws (prize_id);

CREATE TABLE product_reviews (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT                      NOT NULL,
    user_id      BIGINT                      NOT NULL,
    rating       INTEGER                     NOT NULL,
    text         VARCHAR(1000)               NOT NULL,
    author_name  VARCHAR(50)                 NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    title        VARCHAR(100),
    status       VARCHAR(20)                 NOT NULL,
    moderated_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_product_reviews_product_user UNIQUE (product_id, user_id),
    CONSTRAINT fk_product_reviews_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_product_reviews_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_product_reviews_product_status ON product_reviews (product_id, status);
CREATE INDEX idx_product_reviews_status_created ON product_reviews (status, created_at);

CREATE TABLE set_releases (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game         VARCHAR(20)                 NOT NULL,
    name         VARCHAR(150)                NOT NULL,
    release_date DATE                        NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    tentative    BOOLEAN                     NOT NULL,
    description  VARCHAR(1000),
    image_url    VARCHAR(500),
    set_id       BIGINT,
    published    BOOLEAN                     NOT NULL,
    CONSTRAINT fk_set_releases_set FOREIGN KEY (set_id) REFERENCES card_sets (id)
);

CREATE INDEX idx_set_releases_release_date ON set_releases (release_date);

CREATE TABLE set_release_products (
    release_id BIGINT  NOT NULL,
    product_id BIGINT  NOT NULL,
    position   INTEGER NOT NULL,
    PRIMARY KEY (release_id, position),
    CONSTRAINT fk_set_release_products_release FOREIGN KEY (release_id) REFERENCES set_releases (id),
    CONSTRAINT fk_set_release_products_product FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE TABLE news_articles (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(150)                NOT NULL,
    slug         VARCHAR(180)                NOT NULL,
    body         VARCHAR(20000)              NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    summary      VARCHAR(300),
    image_url    VARCHAR(500),
    game         VARCHAR(20),
    published_at TIMESTAMP(6) WITH TIME ZONE,
    published    BOOLEAN                     NOT NULL,
    CONSTRAINT uk_news_articles_slug UNIQUE (slug)
);

CREATE INDEX idx_news_articles_published ON news_articles (published, published_at);

CREATE TABLE info_pages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug       VARCHAR(60)                 NOT NULL,
    title      VARCHAR(150)                NOT NULL,
    body       VARCHAR(50000)              NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    draft      BOOLEAN                     NOT NULL,
    CONSTRAINT uk_info_pages_slug UNIQUE (slug)
);

CREATE TABLE newsletter_subscribers (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                    VARCHAR(254)                NOT NULL,
    created_at               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status                   VARCHAR(20)                 NOT NULL,
    confirm_token_hash       VARCHAR(64),
    confirm_token_expires_at TIMESTAMP(6) WITH TIME ZONE,
    unsubscribe_token_hash   VARCHAR(64),
    confirmed_at             TIMESTAMP(6) WITH TIME ZONE,
    unsubscribed_at          TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_newsletter_subscribers_email UNIQUE (email)
);

CREATE INDEX idx_newsletter_subscribers_confirm ON newsletter_subscribers (confirm_token_hash);
CREATE INDEX idx_newsletter_subscribers_unsubscribe ON newsletter_subscribers (unsubscribe_token_hash);
CREATE INDEX idx_newsletter_subscribers_status ON newsletter_subscribers (status, created_at);

CREATE TABLE ai_usage (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          VARCHAR(10)                 NOT NULL,
    model         VARCHAR(60)                 NOT NULL,
    input_tokens  BIGINT                      NOT NULL,
    output_tokens BIGINT                      NOT NULL,
    cost_micros   BIGINT                      NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    user_id       BIGINT,
    CONSTRAINT fk_ai_usage_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_ai_usage_created_at ON ai_usage (created_at);

