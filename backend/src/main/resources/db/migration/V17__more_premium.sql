-- Phase 12: More Premium. New columns and new tables only: the previous version keeps working on this schema.

-- Themes: light, dark or the device's setting for everyone, and the colour themes for Premium. Null is the default.
ALTER TABLE users ADD COLUMN color_mode VARCHAR(10);
ALTER TABLE users ADD COLUMN color_theme VARCHAR(20);

CREATE TABLE price_alerts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT                      NOT NULL,
    card_id           BIGINT                      NOT NULL,
    variant           VARCHAR(30)                 NOT NULL,
    kind              VARCHAR(10)                 NOT NULL,
    threshold_cents   BIGINT,
    currency          VARCHAR(3),
    percent           INTEGER,
    baseline_cents    BIGINT,
    baseline_currency VARCHAR(3),
    armed             BOOLEAN                     NOT NULL,
    last_triggered_on DATE,
    off_token_hash    VARCHAR(64),
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_price_alerts_user_card_variant_kind UNIQUE (user_id, card_id, variant, kind),
    CONSTRAINT fk_price_alerts_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_price_alerts_card FOREIGN KEY (card_id) REFERENCES cards (id)
);

CREATE INDEX idx_price_alerts_card ON price_alerts (card_id);

CREATE TABLE extra_binders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                      NOT NULL,
    name       VARCHAR(60)                 NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_extra_binders_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_extra_binders_user ON extra_binders (user_id);

CREATE TABLE extra_binder_entries (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    binder_id BIGINT                      NOT NULL,
    card_id   BIGINT                      NOT NULL,
    variant   VARCHAR(30)                 NOT NULL,
    quantity  INTEGER                     NOT NULL,
    added_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_extra_binder_entries_binder_card_variant UNIQUE (binder_id, card_id, variant),
    CONSTRAINT fk_extra_binder_entries_binder FOREIGN KEY (binder_id) REFERENCES extra_binders (id),
    CONSTRAINT fk_extra_binder_entries_card FOREIGN KEY (card_id) REFERENCES cards (id)
);

CREATE INDEX idx_extra_binder_entries_card ON extra_binder_entries (card_id);
