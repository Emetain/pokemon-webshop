-- Phase 11, parts 5 and 7: Premium as a Stripe subscription, and the free card scans. New columns and a new table
-- only: the previous version keeps working on this schema.

ALTER TABLE users ADD COLUMN stripe_customer_id VARCHAR(255);
ALTER TABLE users ADD COLUMN premium_since TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE users ADD COLUMN premium_until TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE users ADD COLUMN premium_forever BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN premium_source VARCHAR(20);
ALTER TABLE users ADD COLUMN free_scans_used INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN premium_consent_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE users ADD CONSTRAINT uk_users_stripe_customer_id UNIQUE (stripe_customer_id);

CREATE TABLE premium_subscriptions (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT                      NOT NULL,
    stripe_subscription_id VARCHAR(255)                NOT NULL,
    plan                   VARCHAR(20),
    status                 VARCHAR(30)                 NOT NULL,
    current_period_end     TIMESTAMP(6) WITH TIME ZONE,
    cancel_at_period_end   BOOLEAN                     NOT NULL,
    consent_at             TIMESTAMP(6) WITH TIME ZONE,
    created_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_premium_subscriptions_stripe_id UNIQUE (stripe_subscription_id),
    CONSTRAINT fk_premium_subscriptions_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_premium_subscriptions_user ON premium_subscriptions (user_id);
